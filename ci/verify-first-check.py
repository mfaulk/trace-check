#!/usr/bin/env python3
"""Runs examples/first-check the way a new user would, and asserts the result.

The demo only means something if the insecure comparison still contains a
secret-dependent branch after optimization: a naive early-exit byte loop is
vectorized into branchless code at opt-level 3, and a demo built on it would
"pass" while proving nothing. So besides the verdicts, this script disassembles
the executable Memcheck analyzed and fails unless the insecure function still
branches on the compared byte. `--self-test` shows that guard is live by
rerunning it on a copy with the `read_volatile` removed, where it must fail.

By default the CLI is installed from this checkout's release archives, with a
`[patch.crates-io]` pointing at them, because the crates are not published yet
(#35). `--installed` skips staging and uses whatever `cargo trace-check` and
Cargo configuration are already on PATH.

Usage: verify-first-check.py [--installed] [--self-test] [--write-readme]
"""

import argparse
import importlib.util
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
import time
import tomllib

REPO = pathlib.Path(__file__).resolve().parent.parent
DEMO = REPO / "examples" / "first-check"
README = DEMO / "README.md"
INSECURE = "first_check::tag_eq_insecure"
SECURE = "first_check::tag_eq_ct"
# The comparison whose outcome depends on the secret byte. Located by text so
# the expected line follows edits to the file instead of being hard-coded.
LEAK_LINE_TEXT = "if byte != supplied[index] {"
VOLATILE_READ = "unsafe { core::ptr::read_volatile(&expected[index]) }"
# Exit codes of `cargo trace-check check`. The insecure contract is declared an
# analyzer regression, so producing LEAK_DETECTED as declared is a success.
EXPECTED = {
    INSECURE: {"exit": 0, "outcome": "LEAK_DETECTED", "policy": "satisfied"},
    SECURE: {"exit": 0, "outcome": "NO_LEAK_OBSERVED", "policy": "satisfied"},
}
BEGIN = "<!-- BEGIN generated by ci/verify-first-check.py --write-readme -->"
END = "<!-- END generated -->"


def load_release_helpers():
    spec = importlib.util.spec_from_file_location("verify_release", REPO / "ci/verify-release.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run(args, *, cwd, env, quiet=False):
    print("+ " + " ".join(map(str, args)), f"(in {cwd})", flush=True)
    result = subprocess.run(args, cwd=cwd, env=env, text=True, capture_output=True)
    if not quiet:
        print(result.stderr[-3000:], end="", flush=True)
    return result


def stage_cli(work):
    """Installs cargo-trace-check from release archives, as a user would."""
    release = load_release_helpers()
    version = tomllib.loads((REPO / "Cargo.toml").read_text())["workspace"]["package"]["version"]
    metadata = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--no-deps", "--format-version", "1"], cwd=REPO, text=True))
    target = pathlib.Path(metadata["target_directory"]) / "release-validation"
    package = ["cargo", "package", "--no-verify", "--allow-dirty"]
    for name in release.CRATES:
        package.extend(["--package", name])
    release.run(package, env=dict(os.environ, CARGO_TARGET_DIR=str(target)))
    extracted = work / "archives"
    extracted.mkdir()
    packages = {
        name: release.check_archive(
            target / "package" / f"{name}-{version}.crate", extracted, name, version)
        for name in release.CRATES
    }
    cargo_home = work / "cargo-home"
    cargo_home.mkdir()
    existing = pathlib.Path(os.environ.get("CARGO_HOME", pathlib.Path.home() / ".cargo"))
    if (existing / "registry").exists():
        (cargo_home / "registry").symlink_to(existing / "registry", target_is_directory=True)
    # The only bridge to the checkout, and only until publication: the demo's
    # manifest names registry versions, and this patch serves them.
    (cargo_home / "config.toml").write_text("[patch.crates-io]\n" + "".join(
        f"{name} = {{ path = {json.dumps(str(path))} }}\n" for name, path in packages.items()))
    env = dict(os.environ, CARGO_HOME=str(cargo_home), CARGO_TARGET_DIR=str(work / "target"))
    env.pop("TRACE_CHECK_TEST_PATH", None)
    installed = work / "installed"
    release.run(["cargo", "install", "--path", str(packages["cargo-trace-check"]),
                 "--root", str(installed)], cwd=work, env=env)
    env["PATH"] = str(installed / "bin") + os.pathsep + env["PATH"]
    return env


def assert_standalone():
    manifest = tomllib.loads((DEMO / "Cargo.toml").read_text())
    assert "workspace" in manifest, "first-check must be its own workspace"
    for kind in ("dependencies", "dev-dependencies", "build-dependencies"):
        for name, spec in manifest.get(kind, {}).items():
            assert not (isinstance(spec, dict) and "path" in spec), (
                f"{name} is a path dependency; the demo must not reach into the checkout")


def leak_line(source):
    lines = [n for n, line in enumerate(source.splitlines(), 1) if LEAK_LINE_TEXT in line]
    assert len(lines) == 1, f"expected exactly one {LEAK_LINE_TEXT!r}, found {lines}"
    return lines[0]


def check_contract(crate_dir, contract, env, artifact_dir=None, fmt="json"):
    args = ["cargo", "trace-check", "check", "--contract", contract, "--format", fmt]
    if artifact_dir is not None:
        args += ["--artifact-dir", str(artifact_dir)]
    return run(args, cwd=crate_dir, env=env, quiet=fmt != "json")


def assert_verdict(contract, result, source):
    expected = EXPECTED[contract]
    assert result.returncode == expected["exit"], (
        f"{contract}: exit {result.returncode}, expected {expected['exit']}\n"
        f"{result.stdout[-3000:]}\n{result.stderr[-3000:]}")
    report = json.loads(result.stdout)
    [entry] = report["contracts"]
    check = entry["check"]
    assert check["outcome"] == expected["outcome"], (contract, check["outcome"], check["message"])
    assert entry["policy"] == expected["policy"], (contract, entry["policy"])
    assert check["calibration"] == "confirmed", (contract, check["calibration"])
    assert check["binding"] == "confirmed", (contract, check["binding"])
    assert check["cases_completed"] > 0, contract
    if expected["outcome"] == "LEAK_DETECTED":
        sites = {finding.get("site") for finding in check["findings"]}
        want = f"src/lib.rs:{leak_line(source)}"
        assert any(site and site.endswith(want) for site in sites), (
            f"{contract}: leak not located at {want}; sites were {sites}")
        print(f"ok: {contract} -> LEAK_DETECTED at {want}")
    else:
        assert not check["findings"], (contract, check["findings"])
        print(f"ok: {contract} -> {check['outcome']} over {check['cases_completed']} cases")


def disassemble(artifact_dir):
    # The Memcheck artifact is the release-profile `tc-check-*` executable; the
    # debug `tc-probe-*` build and build scripts sit beside it.
    executables = [p for p in artifact_dir.glob("*/target/release/tc-check-*")
                   if p.is_file() and os.access(p, os.X_OK)]
    assert len(executables) == 1, f"expected one analyzed executable, found {executables}"
    [executable] = executables
    text = subprocess.run(["objdump", "-d", "--no-show-raw-insn", "-C", str(executable)],
                          check=True, capture_output=True, text=True).stdout
    functions, current = {}, None
    for line in text.splitlines():
        header = re.match(r"^[0-9a-f]+ <(.+)>:$", line)
        if header:
            current = functions.setdefault(header.group(1), [])
        elif current is not None and re.match(r"^\s+[0-9a-f]+:\t", line):
            current.append(line.split("\t")[-1].strip())
    return functions


def byte_branches(instructions):
    """Conditional jumps that directly follow a byte-wide compare."""
    found = []
    for previous, current in zip(instructions, instructions[1:]):
        byte_compare = re.match(r"cmp[b]?\s", previous) and (
            previous.startswith("cmpb") or re.search(r"%[a-d]l\b|%[sd]il\b|%r\d+b\b", previous))
        if byte_compare and re.match(r"j(?!mp)[a-z]+\s", current):
            found.append(f"{previous} ; {current}")
    return found


def branch_guard(artifact_dir):
    """Returns the byte-compare branches in the analyzed tag_eq_insecure."""
    functions = disassemble(artifact_dir)
    bodies = [body for name, body in functions.items()
              if re.fullmatch(r"first_check::tag_eq_insecure(::h[0-9a-f]+)?", name)]
    assert bodies, (
        "tag_eq_insecure is not an out-of-line symbol in the analyzed executable; "
        f"related symbols: {[name for name in functions if 'tag_eq' in name]}")
    return [branch for body in bodies for branch in byte_branches(body)]


def check_insecure(crate_dir, env, work, label):
    """Checks tag_eq_insecure in one copy of the demo, keeping the analyzed artifact."""
    artifacts = work / f"artifacts-{label}"
    result = check_contract(crate_dir, INSECURE, env, artifacts)
    return result, branch_guard(artifacts)


def excerpt(contract, result):
    """The contract's own section of the text report, with checkout paths removed."""
    lines = result.stdout.replace(f"{DEMO}/", "").splitlines()
    start = lines.index(contract)
    end = next(n for n in range(start, len(lines)) if lines[n].lstrip().startswith("policy:"))
    verdict = [line for line in lines if line.startswith("Result:")]
    return "\n".join([f"$ cargo trace-check check --contract {contract}", *lines[start:end + 1],
                      "...", *verdict, "$ echo $?", str(result.returncode)])


def write_readme(env, elapsed):
    blocks = [excerpt(contract, check_contract(DEMO, contract, env, fmt="text"))
              for contract in (INSECURE, SECURE)]
    generated = (f"{BEGIN}\n```text\n" + "\n\n".join(blocks) + "\n```\n\n"
                 f"Demo wall-clock on the machine that generated this excerpt: {elapsed:.0f} s "
                 f"(tests, both checks and the disassembly guard; CLI install excluded).\n{END}")
    text = README.read_text()
    start, end = text.index(BEGIN), text.index(END) + len(END)
    README.write_text(text[:start] + generated + text[end:])
    print(f"wrote {README.relative_to(REPO)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--installed", action="store_true",
                        help="use the cargo trace-check already on PATH")
    parser.add_argument("--self-test", action="store_true",
                        help="prove the disassembly guard fails without read_volatile")
    parser.add_argument("--write-readme", action="store_true",
                        help="regenerate the output excerpt in examples/first-check/README.md")
    parser.add_argument("--keep", type=pathlib.Path, metavar="DIR",
                        help="work in DIR (empty or new) and keep it, for debugging")
    args = parser.parse_args()
    if shutil.which("objdump") is None:
        sys.exit("objdump not found; the branch guard reads the analyzed executable with it")
    assert_standalone()
    started = time.monotonic()
    with tempfile.TemporaryDirectory(prefix="trace-check-first-check-") as temporary:
        work = pathlib.Path(args.keep or temporary)
        work.mkdir(parents=True, exist_ok=True)
        if args.installed:
            env = dict(os.environ)
            env.pop("TRACE_CHECK_TEST_PATH", None)
        else:
            env = stage_cli(work)
        staged = time.monotonic()

        tests = run(["cargo", "test"], cwd=DEMO, env=env)
        assert tests.returncode == 0, tests.stdout + tests.stderr
        print("ok: functional equivalence tests pass")

        source = (DEMO / "src/lib.rs").read_text()
        insecure, branches = check_insecure(DEMO, env, work, "demo")
        assert_verdict(INSECURE, insecure, source)
        assert branches, "tag_eq_insecure has no conditional branch on a compared byte"
        print(f"ok: analyzed tag_eq_insecure branches on the byte: {branches[0]}")
        secure = check_contract(DEMO, SECURE, env)
        assert_verdict(SECURE, secure, source)
        elapsed = time.monotonic() - staged
        print(f"demo wall-clock (excluding CLI install): {elapsed:.1f} s")

        if args.self_test:
            mutant = work / "mutant"
            shutil.copytree(DEMO, mutant, ignore=shutil.ignore_patterns("target"))
            lib = mutant / "src/lib.rs"
            text = lib.read_text()
            assert text.count(VOLATILE_READ) == 1, "self-test cannot find the volatile read"
            lib.write_text(text.replace(VOLATILE_READ, "expected[index]"))
            result, mutant_branches = check_insecure(mutant, env, work, "mutant")
            assert not mutant_branches, (
                "self-test: the guard still sees a byte branch with read_volatile removed, "
                f"so it would not catch branch erasure: {mutant_branches}")
            outcome = json.loads(result.stdout)["contracts"][0]["check"]["outcome"]
            print("ok: self-test: without read_volatile the branch is erased and the guard "
                  f"fails (the analyzer reports {outcome} for that version)")

        if args.write_readme:
            write_readme(env, elapsed)
    print(f"first-check demo verified in {time.monotonic() - started:.0f} s total")


if __name__ == "__main__":
    main()
