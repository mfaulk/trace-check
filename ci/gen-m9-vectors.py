#!/usr/bin/env python3
"""Generates the audit adapters' functional test vectors from an independent oracle.

Side-channel testing is not arithmetic testing, and conflating them is how an
audit ends up analyzing code that computes the wrong thing. An adapter can
mishandle byte order, truncate an input, build a Montgomery value incorrectly,
or consume the wrong part of a result — and every one of those leaves
trace-check reporting confidently about an operation that is not the one the
contract names.

So the expected values here are computed in Python's arbitrary-precision
integers, which share no code with `crypto-bigint`. A byte-order mistake in the
adapter cannot cancel against the implementation under audit, because the
reference does not use it.

Deterministic by construction: the pseudorandom operands are a SHA-256 counter
stream over a fixed seed, so regenerating produces byte-identical output and
the committed fixture is reviewable as a diff.

Usage:
    ci/gen-m9-vectors.py                 # rewrite the committed fixture
    ci/gen-m9-vectors.py --check         # fail if the fixture is out of date
"""

import argparse
import hashlib
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
FIXTURE = REPO / "examples" / "crypto-bigint-audit" / "tests" / "vectors" / "generated.rs"

SEED = b"trace-check m9 crypto-bigint audit vectors v1"
RANDOM_CASES = 24

# 2^256 - 2^224 + 2^192 + 2^96 - 1, the NIST P-256 field prime. Written as the
# arithmetic expression rather than as a hex literal, so this file and
# `monty.rs`'s hex constant are two independent statements of the same number.
P256 = 2**256 - 2**224 + 2**192 + 2**96 - 1

MASK = 2**256 - 1


def stream(count):
    """`count` deterministic 256-bit values from a SHA-256 counter stream."""
    for index in range(count):
        digest = hashlib.sha256(SEED + index.to_bytes(4, "big")).digest()
        yield int.from_bytes(digest, "big")


def boundaries():
    """The values where carry propagation, reduction and limb edges turn on."""
    return [
        0,
        1,
        MASK,
        MASK - 1,
        2**64 - 1,  # fills the lowest limb exactly
        2**64,  # the first carry into limb 1
        2**192,  # the lowest bit of the highest limb
        2**255,  # the top bit
        P256 - 1,
        P256,  # congruent to zero
        P256 + 1,
    ]


def operands():
    """Every pair this fixture covers: boundaries crossed, then the stream."""
    edges = boundaries()
    pairs = [(left, right) for left in edges for right in edges]
    stream_values = list(stream(RANDOM_CASES * 2))
    pairs += list(zip(stream_values[::2], stream_values[1::2]))
    # Each stream value against each boundary, so a value that is interesting
    # on one side is also exercised on the other.
    pairs += [(value, edge) for value in stream_values[:4] for edge in edges]
    return pairs


def hex256(value):
    """Big-endian hex. A reviewable diff needs a human-readable number."""
    return f'"{value:064x}"'


def render():
    lines = [
        "// @generated by ci/gen-m9-vectors.py -- do not edit.",
        "//",
        "// Expected values computed in Python's arbitrary-precision integers, which",
        "// share no code with `crypto-bigint`: a byte-order or truncation mistake in",
        "// an adapter cannot cancel against the implementation under audit.",
        "//",
        "// Operands are the carry/reduction/limb-edge boundaries crossed with each",
        "// other, plus a SHA-256 counter stream over a fixed seed. Regenerate with",
        "// `ci/gen-m9-vectors.py` and review the diff.",
        "//",
        "// Big-endian hex, 64 digits, decoded by `tests/functional.rs`.",
        "",
        "/// `left`, `right`, `(left + right) mod 2^256`.",
        "pub const ADD: &[(&str, &str, &str)] = &[",
    ]
    pairs = operands()
    for left, right in pairs:
        total = (left + right) & MASK
        lines.append(f"    ({hex256(left)}, {hex256(right)}, {hex256(total)}),")
    lines += [
        "];",
        "",
        "/// `left`, `right`, `choice`, and the candidate that must be selected.",
        "pub const SELECT: &[(&str, &str, u8, &str)] = &[",
    ]
    # Every choice byte against a fixed pair pins the `& 1` reading; the operand
    # pairs then vary the candidates for both outcomes.
    fixed_left = int("11" * 32, 16)
    fixed_right = int("22" * 32, 16)
    for byte in range(256):
        chosen = fixed_right if byte & 1 else fixed_left
        lines.append(
            f"    ({hex256(fixed_left)}, {hex256(fixed_right)}, "
            f"0x{byte:02x}, {hex256(chosen)}),"
        )
    for left, right in pairs:
        for byte in (0x00, 0x01):
            chosen = right if byte & 1 else left
            lines.append(
                f"    ({hex256(left)}, {hex256(right)}, 0x{byte:02x}, {hex256(chosen)}),"
            )
    lines += [
        "];",
        "",
        "/// `left`, `right`, `(left * right) mod p` for the P-256 field prime.",
        "pub const MUL_MOD_P256: &[(&str, &str, &str)] = &[",
    ]
    for left, right in pairs:
        product = (left * right) % P256
        lines.append(f"    ({hex256(left)}, {hex256(right)}, {hex256(product)}),")
    lines += [
        "];",
        "",
        "/// The modulus the Montgomery adapters are defined over.",
        f"pub const P256_PRIME: &str = {hex256(P256)};",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed fixture differs from freshly generated output",
    )
    arguments = parser.parse_args()

    rendered = render()
    if arguments.check:
        if not FIXTURE.is_file():
            sys.exit(f"FAIL: {FIXTURE} does not exist; run ci/gen-m9-vectors.py")
        if FIXTURE.read_text() != rendered:
            sys.exit(
                f"FAIL: {FIXTURE.relative_to(REPO)} is out of date with "
                "ci/gen-m9-vectors.py; regenerate it and review the diff"
            )
        print(f"{FIXTURE.relative_to(REPO)} matches the generator")
        return

    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(rendered)
    cases = rendered.count("\n    (")
    print(f"wrote {FIXTURE.relative_to(REPO)}: {cases} case(s)")


if __name__ == "__main__":
    main()
