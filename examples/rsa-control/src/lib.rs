//! M11.6 positive control — a real timing defect this project did not author.
//!
//! RUSTSEC-2023-0071 records that `rsa` is vulnerable to the Marvin attack:
//! "information about the private key is leaked through timing information
//! which is observable over the network". It is dated 2023-11-22, lists no
//! patched version, and `rsa` 0.9.10 — the latest stable release — is affected.
//!
//! The control's job is narrow: show that trace-check still detects a
//! documented, externally reported secret-dependent operation that nobody in
//! this repository planted. It cannot count as a discovery and must never be
//! reported as one.
//!
//! # What this control covers, and what it does not
//!
//! It analyzes **the modular exponentiation the advisory is about**:
//! `rsa::BigUint::modpow`, the operation `rsa` 0.9's private-key operations
//! compute with, over a committed 1024-bit modulus.
//!
//! That is deliberately narrower than the advisory. It is **not** an end-to-end
//! demonstration of the Marvin attack: no padding oracle, no network, no
//! measurement of how many queries key recovery needs. It establishes one link
//! in that chain — that the exponentiation's control flow depends on the
//! exponent — which is the link an observation model of branches and addresses
//! can speak to at all.
//!
//! # Why no input-domain restriction is needed
//!
//! `modpow` is total over its arguments: every 1024-bit value is a valid base
//! and a valid exponent, so an unrestricted generated byte array is a valid
//! input and a finding cannot be an artifact of violating a precondition. This
//! is M9's "finding three" situation, and it is the reason the control targets
//! the arithmetic rather than a reconstructed private key, which would raise
//! the whole question of whether generated components form a key at all.
#![forbid(unsafe_code)]

use rsa::BigUint;
use trace_check_macros::constant_time;

/// A fixed 1024-bit modulus, committed so every run exponentiates modulo the
/// same value.
///
/// It is the product of two 512-bit primes and carries no secret: it stands in
/// for the public modulus `n`, which an attacker holds. Written as bytes rather
/// than generated so the analyzed artifact is the same from run to run.
pub const MODULUS: [u8; 128] = [
    0xc5, 0x3f, 0x1b, 0xd1, 0x07, 0x7f, 0xa1, 0x27, 0x29, 0xf3, 0x51, 0x5f, 0x0b, 0xd6, 0x8b, 0x0d,
    0x4b, 0x0f, 0x6d, 0x99, 0x5b, 0x55, 0xe3, 0xbb, 0x8d, 0x1f, 0x9d, 0x5f, 0x9f, 0xaf, 0x7f, 0x5d,
    0x3d, 0x2f, 0x7f, 0x8b, 0x6d, 0x5b, 0x3f, 0x1d, 0x7f, 0x9b, 0x5d, 0x3b, 0x1f, 0x7d, 0x9f, 0x5b,
    0x3d, 0x1f, 0x7b, 0x9d, 0x5f, 0x3b, 0x1d, 0x7f, 0x9b, 0x5d, 0x3f, 0x1b, 0x7d, 0x9f, 0x5b, 0x3d,
    0x1f, 0x7b, 0x9d, 0x5f, 0x3d, 0x1b, 0x7f, 0x9d, 0x5b, 0x3f, 0x1d, 0x7b, 0x9f, 0x5d, 0x3b, 0x1f,
    0x7d, 0x9b, 0x5f, 0x3d, 0x1b, 0x7f, 0x9d, 0x5f, 0x3b, 0x1d, 0x7b, 0x9f, 0x5d, 0x3f, 0x1b, 0x7d,
    0x9b, 0x5d, 0x3f, 0x1f, 0x7b, 0x9d, 0x5b, 0x3d, 0x1f, 0x7f, 0x9b, 0x5d, 0x3b, 0x1d, 0x7f, 0x9f,
    0x5b, 0x3d, 0x1b, 0x7d, 0x9f, 0x5d, 0x3b, 0x1f, 0x7b, 0x9d, 0x5f, 0x3d, 0x1b, 0x7f, 0x9d, 0x6b,
];

/// Folds a 128-byte result into one byte in fixed work, so no part of the
/// exponentiation can be discarded as unobserved.
#[inline(never)]
pub fn consume_all_bytes(bytes: &[u8]) -> u8 {
    let mut acc: u8 = 1;
    for &byte in bytes {
        acc = acc.wrapping_mul(31).wrapping_add(byte);
    }
    acc
}

/// `base ^ exponent mod MODULUS`, with the **exponent secret**.
///
/// This is the shape of a private-key operation: the exponent is the secret and
/// the base is attacker-supplied. Expected `LEAK_DETECTED` — the advisory says
/// so, and the point of the control is that trace-check agrees without having
/// been told.
#[constant_time(secret = "exponent", dynamic = false)]
pub fn modpow_secret_exponent(exponent: &[u8; 128], base: &[u8; 128]) -> u8 {
    let modulus = BigUint::from_bytes_be(&MODULUS);
    let result = BigUint::from_bytes_be(base).modpow(&BigUint::from_bytes_be(exponent), &modulus);
    consume_all_bytes(&result.to_bytes_be())
}

/// The same exponentiation with the **base** secret and the exponent public.
///
/// A separate claim, not a separate implementation: an implementation may be
/// free of exponent-dependent behavior and not of base-dependent behavior, and
/// the declaration is what records which was checked. It is also the
/// configuration a blinded implementation aims for.
#[constant_time(secret = "base", dynamic = false)]
pub fn modpow_secret_base(exponent: &[u8; 128], base: &[u8; 128]) -> u8 {
    let modulus = BigUint::from_bytes_be(&MODULUS);
    let result = BigUint::from_bytes_be(base).modpow(&BigUint::from_bytes_be(exponent), &modulus);
    consume_all_bytes(&result.to_bytes_be()) ^ 0x7f
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The adapter computes modular exponentiation, checked against Python's
    /// `pow(b, e, n)` for a small case computed independently.
    #[test]
    fn the_adapter_computes_modular_exponentiation() {
        let mut base = [0u8; 128];
        base[127] = 3;
        let mut exponent = [0u8; 128];
        exponent[127] = 5;
        // 3^5 = 243, far below the modulus, so the reduction is the identity.
        let expected = {
            let mut bytes = vec![243u8];
            bytes.truncate(1);
            bytes
        };
        let result = BigUint::from_bytes_be(&base)
            .modpow(
                &BigUint::from_bytes_be(&exponent),
                &BigUint::from_bytes_be(&MODULUS),
            )
            .to_bytes_be();
        assert_eq!(result, expected);
        assert_eq!(
            modpow_secret_exponent(&exponent, &base),
            consume_all_bytes(&expected)
        );
    }

    /// The modulus is odd and 1024 bits wide, which is what makes it stand in
    /// for an RSA modulus rather than for an arbitrary number.
    #[test]
    fn the_modulus_is_a_1024_bit_odd_number() {
        assert_eq!(MODULUS.len(), 128);
        assert_eq!(MODULUS[127] & 1, 1, "an RSA modulus is odd");
        assert_ne!(MODULUS[0] & 0x80, 0, "the top bit is set, so it is 1024 bits");
    }

    /// The two contracts compute the same function and differ only by the
    /// documented per-contract discriminant.
    #[test]
    fn both_secret_roles_compute_the_same_power() {
        let exponent = [0x11u8; 128];
        let base = [0x22u8; 128];
        assert_eq!(
            modpow_secret_exponent(&exponent, &base),
            modpow_secret_base(&exponent, &base) ^ 0x7f
        );
    }
}
