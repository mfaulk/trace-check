//! An ordinary Rust library whose real functions are both dynamically tested
//! and symbolically verified.
//!
//! Each implementation is defined **once**, here. Nothing in this crate is a
//! verification harness, and nothing in it is written for an analyzer:
//!
//! ```sh
//! cargo trace-check test                                   # M3, Valgrind
//! cargo trace-check verify --contract crypto::tag::verify_tag   # M5, BINSEC
//! ```
//!
//! Both commands analyze code compiled from the same source.
//!
//! # Why `no_std`
//!
//! Symbolic verification links this library into a freestanding static ELF with
//! no libc and no runtime, so there is nothing but the primitive to explore.
//! `std` is enabled under `cfg(test)` so the M3 dynamic checks — which need
//! Valgrind client requests and the ordinary test harness — still work.
//!
//! # The crate deliberately contains vulnerable implementations
//!
//! `verify_tag_volatile_early_exit`, `substitute_indexed` and
//! `substitute_mode` are expected to be *detected*, so a full
//! `cargo trace-check test` run exits 1 by design, exactly as
//! `examples/consumer-crate` does. See `README.md` for which invocation
//! demonstrates what.
#![cfg_attr(not(test), no_std)]

pub mod controls;
pub mod lookup;
pub mod reduce;
pub mod tag;

#[cfg(test)]
mod tests {
    use trace_check_test::{assert_constant_time, ct_test};

    // `#[ct_test(target = "tag::verify_tag")]` resolves the contract's paths
    // relative to this module, so the modules have to be in scope here.
    use crate::{controls, lookup, reduce, tag};

    /// A tag built at run time. A compile-time constant would let the
    /// optimizer pass an immediate and never read the marked storage, which is
    /// the hazard `trace_check_test::analyze1` documents.
    fn secret_tag() -> [u8; 16] {
        let mut tag = [0u8; 16];
        let mut index = 0usize;
        while index < 16 {
            tag[index] = (index as u8).wrapping_mul(31).wrapping_add(7);
            index += 1;
        }
        tag
    }

    /// The constant-time tag comparison: no modeled secret-dependent behavior
    /// on the path this test exercises.
    #[ct_test(target = "tag::verify_tag")]
    fn verify_tag_is_constant_time() {
        let supplied = [0u8; 16];
        // The `_ct` adapter generated by `#[constant_time]` owns and marks the
        // declared secret and calls the untouched function with it in its
        // declared slot, so the contract cannot be claimed without exercising
        // it.
        let accepted = tag::verify_tag_ct(secret_tag(), &supplied);
        assert!(!accepted, "a mismatching tag must be rejected");
    }

    /// The naive early exit, which the compiler vectorizes: no leak is
    /// observed, and that is the honest result for the compiled code.
    #[ct_test(target = "tag::verify_tag_early_exit")]
    fn early_exit_was_erased_by_the_compiler() {
        let supplied = [0u8; 16];
        let accepted = tag::verify_tag_early_exit_ct(secret_tag(), &supplied);
        assert!(!accepted);
    }

    /// The early exit that survives optimization: expected to be detected as a
    /// secret-dependent branch.
    #[ct_test(target = "tag::verify_tag_volatile_early_exit")]
    fn volatile_early_exit_leaks() {
        let supplied = [0u8; 16];
        let accepted = tag::verify_tag_volatile_early_exit_ct(secret_tag(), &supplied);
        assert!(!accepted);
    }

    /// The masked scan: no modeled secret-dependent behavior.
    #[ct_test(target = "lookup::substitute")]
    fn substitute_is_constant_time() {
        let selected = lookup::substitute_ct(secret_index());
        assert_eq!(selected, lookup::substitute(secret_index()));
    }

    /// The secret-indexed load: expected to be detected as a secret-dependent
    /// address.
    #[ct_test(target = "lookup::substitute_indexed")]
    fn substitute_indexed_leaks() {
        let selected = lookup::substitute_indexed_ct(secret_index());
        assert_eq!(selected, lookup::substitute_indexed(secret_index()));
    }

    /// The milestone's key asymmetry, from the dynamic side: with `mode == 0`
    /// the safe path runs and **nothing is observed**. The vulnerability is
    /// still there, on a path this test never visits, and only
    /// `cargo trace-check verify` finds it.
    #[ct_test(target = "lookup::substitute_mode")]
    fn substitute_mode_observes_nothing_on_the_safe_path() {
        let selected = lookup::substitute_mode_ct(secret_index(), 0);
        assert_eq!(selected, lookup::substitute(secret_index()));
    }

    /// The per-byte control: the final secret byte reaches a load address, so
    /// this is expected to be detected.
    #[ct_test(target = "controls::tail_byte_probe")]
    fn tail_byte_probe_leaks() {
        let supplied = [0u8; 16];
        let _ = controls::tail_byte_probe_ct(secret_tag(), &supplied);
    }

    /// Branching on a public input is permitted: no finding here.
    #[ct_test(target = "controls::public_branch")]
    fn a_public_branch_is_not_a_leak() {
        let mixed = controls::public_branch_ct(secret_index(), 1);
        assert_eq!(mixed, controls::public_branch(secret_index(), 1));
    }

    /// Conditional subtraction over a 32-bit secret.
    #[ct_test(target = "reduce::reduce_once")]
    fn reduce_once_is_checked() {
        let reduced = reduce::reduce_once_ct(secret_value(), 0x1000_0001);
        assert_eq!(reduced, reduce::reduce_once(secret_value(), 0x1000_0001));
    }

    /// The masked reduction.
    #[ct_test(target = "reduce::reduce_once_masked")]
    fn masked_reduction_is_constant_time() {
        let reduced = reduce::reduce_once_masked_ct(secret_value(), 0x1000_0001);
        assert_eq!(
            reduced,
            reduce::reduce_once_masked(secret_value(), 0x1000_0001)
        );
    }

    /// Both substitutions agree for every index, which is the functional
    /// property the constant-time rewrite has to preserve. An ordinary unit
    /// test, needing no instrumentation.
    #[test]
    fn both_substitutions_agree_for_every_index() {
        for index in 0..=u8::MAX {
            assert_eq!(lookup::substitute(index), lookup::substitute_indexed(index));
        }
    }

    /// Both reductions agree, including at the modulus boundary.
    #[test]
    fn both_reductions_agree() {
        for value in [0u32, 1, 0x1000_0000, 0x1000_0001, 0x2000_0002, u32::MAX] {
            assert_eq!(
                reduce::reduce_once(value, 0x1000_0001),
                reduce::reduce_once_masked(value, 0x1000_0001)
            );
        }
    }

    fn secret_index() -> u8 {
        // Derived at run time for the same reason `secret_tag` is.
        secret_tag()[3] & 15
    }

    fn secret_value() -> u32 {
        u32::from_le_bytes([secret_tag()[0], secret_tag()[1], 0x10, 0x20])
    }

    /// `assert_constant_time!` still works without a contract, for a secret
    /// that is not a declared parameter of an annotated function.
    #[ct_test]
    fn a_contractless_assertion_still_works() {
        let supplied = [0u8; 16];
        let accepted = assert_constant_time!(
            secret = secret_tag(),
            call = |expected| tag::verify_tag(expected, &supplied),
        );
        assert!(!accepted);
    }
}
