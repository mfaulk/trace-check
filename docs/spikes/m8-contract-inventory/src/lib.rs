#![no_std]

/// What a generated record looks like. Hand-written here; the macro would emit
/// this shape.
macro_rules! record {
    ($name:ident, $payload:expr) => {
        const _: () = {
            const TEXT: &str = $payload;
            #[used]
            #[link_section = ".trace_check.contracts"]
            static $name: [u8; 8 + 2 + 4 + TEXT.len()] = {
                let mut out = [0u8; 8 + 2 + 4 + TEXT.len()];
                let magic = b"TCCONTR1";
                let mut i = 0;
                while i < 8 {
                    out[i] = magic[i];
                    i += 1;
                }
                // schema version, u16 little-endian
                out[8] = 1;
                out[9] = 0;
                // payload length, u32 little-endian
                let len = TEXT.len() as u32;
                out[10] = (len & 0xff) as u8;
                out[11] = ((len >> 8) & 0xff) as u8;
                out[12] = ((len >> 16) & 0xff) as u8;
                out[13] = ((len >> 24) & 0xff) as u8;
                let bytes = TEXT.as_bytes();
                let mut j = 0;
                while j < bytes.len() {
                    out[14 + j] = bytes[j];
                    j += 1;
                }
                out
            };
        };
    };
}

pub mod alpha {
    record!(R_ALPHA_PROBE, r#"{"id":"spike::alpha::probe","dynamic":false}"#);
    pub fn probe(key: u8) -> u8 {
        key ^ 0x5a
    }
}

pub mod beta {
    record!(R_BETA_PROBE, r#"{"id":"spike::beta::probe","dynamic":true}"#);
    pub fn probe(key: u8) -> u8 {
        key.wrapping_mul(3)
    }
}

#[cfg(feature = "fast")]
pub mod gated {
    record!(R_GATED_FAST, r#"{"id":"spike::gated::fast","dynamic":false}"#);
    pub fn fast(key: u8) -> u8 {
        key
    }
}

/// A function *generated by another macro*, then annotated. The record must
/// appear because the annotation expanded, not because the source was parsed.
macro_rules! declare {
    ($name:ident, $mask:expr) => {
        record!(R_GEN, concat!(r#"{"id":"spike::generated::"#, stringify!($name), r#"","dynamic":false}"#));
        pub fn $name(key: u8) -> u8 {
            key & $mask
        }
    };
}

pub mod generated {
    declare!(woven, 0x3f);
}

/// Twenty more modules, to push the build across many codegen units.
macro_rules! bulk {
    ($($module:ident),*) => {
        $(
            pub mod $module {
                record!(R_BULK, concat!(r#"{"id":"spike::"#, stringify!($module), r#"::probe","dynamic":true}"#));
                pub fn probe(key: u8) -> u8 {
                    key.wrapping_add(7)
                }
            }
        )*
    };
}

